// Generates `review/src/M3e/Review/Families.elm` from `config/slots.json`'s
// `_families.families` — the source `gen-family-package.js` reads to emit the
// `elm-m3e-families` package (`elm-m3e-families/src/M3e/Family/*.elm`).
//
// WHY THIS EXISTS
// ---------------
// `NoFamilyMemberDrift` (jackhp95/elm-review-cem) checks a generated family
// module's imports against the family CONFIG's declared member list. An
// elm-review rule is Elm and cannot read JSON at review time, so the config
// is flattened and baked into a generated Elm module here — the same shape
// `M3eUtilityNames` uses for `NoProprietaryDsClasses`, and `M3e.Review.Facts`
// uses for the facts-driven rules.
//
// "Flattened" means each family's `root` (if any) plus every `members[].component`
// collapsed into one `members : List String` — the exact set `gen-family-package.js`
// makes the family module `import M3e.Element.<X>` for (verified 1:1 against
// every currently-generated `M3e.Component.*.elm` when this generator was written).
//
// Run `node review/scripts/gen-m3e-family-config.mjs` to regenerate; `--check`
// re-runs to a temp file and byte-compares, so committed drift is a gate failure
// rather than silent staleness. Mirrors `gen-m3e-utility-names.mjs`.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const CONFIG = path.join(ROOT, "..", "..", "..", "..", "inputs", "cem", "config", "slots.json");
const OUTPUT_PATH = path.join(ROOT, "src", "M3e", "Review", "Families.elm");

function flattenedMembers(spec) {
  const members = spec.root ? [spec.root] : [];
  for (const member of spec.members ?? []) {
    members.push(member.component);
  }
  return members;
}

function elmStringList(strings) {
  if (strings.length === 0) {
    return "[]";
  }
  return strings.map((s) => `"${s}"`).join(", ");
}

function generate() {
  const config = JSON.parse(fs.readFileSync(CONFIG, "utf8"));
  const families = config._families?.families;
  if (!families || Object.keys(families).length === 0) {
    throw new Error(`${CONFIG} has no _families.families — refusing to generate an empty family list`);
  }

  const names = Object.keys(families).sort();
  const entries = names
    .map((name) => {
      const members = flattenedMembers(families[name]);
      return `    , { family = "${name}", members = [ ${elmStringList(members)} ] }`;
    })
    .join("\n")
    .replace(/^    , /, "    [ ");

  return `module M3e.Review.Families exposing (families)

{-| GENERATED by \`review/scripts/gen-m3e-family-config.mjs\` — do not edit.

The M3e family config (\`config/slots.json\`'s \`_families.families\`), flattened
to the shape \`NoFamilyMemberDrift\` (jackhp95/elm-review-cem) expects: one entry
per family, \`members\` carrying the family's \`root\` (if any) plus every
declared member's component name — the exact set \`gen-family-package.js\`
imports from \`M3e.Element.*\` into the generated \`M3e.Component.<F>\` module.
${names.length} families.

@docs families

-}


{-| Every M3e family's name and flattened member-component list.
-}
families : List { family : String, members : List String }
families =
${entries}
    ]
`;
}

function main() {
  const generated = generate();
  const checkMode = process.argv.includes("--check");

  if (!checkMode) {
    fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
    fs.writeFileSync(OUTPUT_PATH, generated);
    console.log(`gen-m3e-family-config: wrote ${OUTPUT_PATH}`);
    return;
  }

  if (!fs.existsSync(OUTPUT_PATH)) {
    console.error(`check-m3e-family-config: FAIL — ${OUTPUT_PATH} does not exist. Run \`node review/scripts/gen-m3e-family-config.mjs\`.`);
    process.exit(1);
  }

  const committed = fs.readFileSync(OUTPUT_PATH, "utf8");
  if (committed === generated) {
    console.log("check-m3e-family-config: OK — committed family config matches config/slots.json.");
    return;
  }

  const tmp = path.join(os.tmpdir(), `gen-m3e-family-config-check-${process.pid}.elm`);
  fs.writeFileSync(tmp, generated);
  console.error(
    "check-m3e-family-config: FAIL — committed review/src/M3e/Review/Families.elm has drifted from " +
      "config/slots.json's _families.families.\n" +
      `  fresh output: ${tmp}\n` +
      "  Regenerate with `node review/scripts/gen-m3e-family-config.mjs` and commit.",
  );
  process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
