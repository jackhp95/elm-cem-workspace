// Generates `review/src/M3eUtilityNames.elm` from tailwind-m3e-web's
// `generated/utilities.json`.
//
// WHY THIS EXISTS
// ---------------
// `NoProprietaryDsClasses` permits `m3e-*` classes — they set a component's own
// documented CSS custom properties, which is styling THROUGH m3e rather than
// around it. It used to permit them with `String.startsWith "m3e-"`, a guess. So
// `m3e-crd-padding-4` (typo) or `m3e-totally-fake-thing` passed the rule and then
// rendered nothing: precisely the dead-class failure the rule was written to catch
// for `ds-`/`t-` prefixes.
//
// The authoritative list is generated by tailwind-m3e-web from `data/cem-facts.json`
// at the same moment it writes `utilities.css`. An elm-review rule is Elm and cannot
// read JSON at runtime, so the list is baked into a generated Elm module here — the
// same shape as `M3e.Review.Facts`, which is how every other facts-driven rule in
// this repo gets its data.
//
// Run `node scripts/gen-m3e-utility-names.mjs` to regenerate;
// `--check` re-runs to a temp file and byte-compares, so committed drift is a gate
// failure rather than a silent staleness. Mirrors `docs/scripts/gen-compose-attrs.mjs`.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const MANIFEST = path.join(ROOT, "..", "..", "tailwind-m3e-web", "generated", "utilities.json");
const OUTPUT_PATH = path.join(ROOT, "src", "M3eUtilityNames.elm");

function generate() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  const utilities = manifest.utilities;
  if (!Array.isArray(utilities) || utilities.length === 0) {
    throw new Error(`${MANIFEST} has no utilities — refusing to generate an empty allow-list`);
  }

  const entries = utilities.map((u) => `    , "${u}"`).join("\n").replace(/^    , /, "    [ ");

  return `module M3eUtilityNames exposing (names)

{-| GENERATED by \`review/scripts/gen-m3e-utility-names.mjs\` — do not edit.

The real \`m3e-*\` Tailwind utility names, from tailwind-m3e-web's
\`generated/utilities.json\` (itself generated from \`data/cem-facts.json\`
alongside \`generated/utilities.css\`). ${utilities.length} names.

\`NoProprietaryDsClasses\` checks membership against this instead of guessing on the
\`m3e-\` prefix, so a typo like \`m3e-crd-padding-4\` is reported rather than silently
rendering nothing.

Names carry no trailing \`-*\`: \`@utility m3e-card-padding-*\` appears here as
\`m3e-card-padding\`. A class matches when it equals a name or starts with the name
plus \`-\`, which is what Tailwind's \`-*\` means.

@docs names

-}


{-| Every real \`m3e-*\` utility name, sorted.
-}
names : List String
names =
${entries}
    ]
`;
}

function main() {
  const generated = generate();
  const checkMode = process.argv.includes("--check");

  if (!checkMode) {
    fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
    fs.writeFileSync(OUTPUT_PATH, generated);
    console.log(`gen-m3e-utility-names: wrote ${OUTPUT_PATH}`);
    return;
  }

  if (!fs.existsSync(OUTPUT_PATH)) {
    console.error(`check-m3e-utility-names: FAIL — ${OUTPUT_PATH} does not exist. Run \`node scripts/gen-m3e-utility-names.mjs\`.`);
    process.exit(1);
  }

  const committed = fs.readFileSync(OUTPUT_PATH, "utf8");
  if (committed === generated) {
    console.log("check-m3e-utility-names: OK — committed names match the generator's current output.");
    return;
  }

  const tmp = path.join(os.tmpdir(), `gen-m3e-utility-names-check-${process.pid}.elm`);
  fs.writeFileSync(tmp, generated);
  console.error(
    "check-m3e-utility-names: FAIL — committed review/src/M3eUtilityNames.elm has drifted from " +
      "tailwind-m3e-web's generated/utilities.json.\n" +
      `  fresh output: ${tmp}\n` +
      "  Regenerate with `node review/scripts/gen-m3e-utility-names.mjs` and commit.",
  );
  process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
