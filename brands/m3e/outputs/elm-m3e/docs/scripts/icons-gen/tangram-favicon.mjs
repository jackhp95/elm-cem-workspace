// Generates docs/public/favicon.svg as the tangram mark, baking the default
// theme's resolved primary color via @material/material-color-utilities —
// NOT `currentColor` (the previous palette-glyph favicon's mechanism), because
// the live in-session favicon-color port (`setFaviconColor`, see
// specs/2026-08-08-theme-editor-drawer-design.md) needs a real hex to start
// from and rewrite via a data: URI; `currentColor` has nothing for that port
// to read.
//
// Geometry mirrors docs/app/Logo.elm's two `d` attribute strings exactly —
// keep both in sync if the tangram geometry ever changes; Elm and this Node
// script can't literally share the constant across the language boundary.
//
// No favicon.ico, matching the existing convention this replaces (see the
// header comment this generator's predecessor, brand-images.mjs, already
// carries: a raster has no CSS context, so a fixed favicon.ico would bake in
// a color nobody chose — same reasoning applies here, doubly so now that the
// fill is a real theme-derived hex rather than currentColor).
//
// Runs AFTER brand-images.mjs in the gen:brand-images pipeline step
// (docs/package.json) — brand-images.mjs still owns og-card.png generation
// (untouched by this spec's scope) and writes its own (now-superseded)
// favicon.svg first; this script overwrites that output with the tangram.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { register } from "node:module";

// Workaround for an upstream ESM-extension bug in
// @material/material-color-utilities@0.4.0 — see
// scripts/icons-gen/lib/esm-extension-fallback-loader.mjs for details. Must
// run before the (dynamic) import below; static imports are hoisted ahead
// of any code in this module, so the package import can't be static here.
register("./lib/esm-extension-fallback-loader.mjs", import.meta.url);
const { Hct, SchemeNeutral, MaterialDynamicColors, argbFromHex, hexFromArgb } = await import(
  "@material/material-color-utilities"
);

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..", "..", "..");

// Keep in sync with docs/app/Theme.elm's `init.seed` (theme-editor-drawer
// plan, Task 7) and Shared.elm's current default seed.
const DEFAULT_SEED = "#6750A4";

const PATHS = [
  "m0 0 566 566H0z",
  "M566 0v535L299 267.973z",
];

export function resolvePrimaryHex(seedHex) {
  const sourceHct = Hct.fromInt(argbFromHex(seedHex));
  const scheme = new SchemeNeutral(sourceHct, /* isDark */ false, /* contrastLevel */ 0);
  return hexFromArgb(MaterialDynamicColors.primary.getArgb(scheme));
}

export function buildSvg(primaryHex) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 566 566" role="img" aria-label="elm-m3e">
  <!-- GENERATED by docs/scripts/icons-gen/tangram-favicon.mjs — do not edit.
       Geometry mirrors docs/app/Logo.elm's tangram paths. -->
  <path fill="${primaryHex}" d="${PATHS[0]}"/>
  <path fill="${primaryHex}" d="${PATHS[1]}"/>
</svg>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const primaryHex = resolvePrimaryHex(DEFAULT_SEED);
  writeFileSync(resolve(REPO, "docs", "public", "favicon.svg"), buildSvg(primaryHex));
  console.log(`favicon.svg regenerated — baked primary: ${primaryHex}`);
}
