// Generates the brand images from the REAL Material Symbols `palette` glyph —
// the same icon the app bar renders (docs/app/Shared.elm: M3e.Icon.name "palette"):
//
//   docs/public/favicon.svg   bare glyph, currentColor (deterministic, drift-gated)
//   docs/public/og-card.png   1200x630 social card    (raster, NOT drift-gated)
//
// There is deliberately NO favicon.ico. The favicon is `fill="currentColor"`, and
// a raster has no CSS context to resolve that against — resvg renders it opaque
// black, which is a colour nobody chose. Site.elm registers only favicon.svg, and
// the .ico's last consumers (the route social-card refs) moved to og-card.png, so
// the fallback had no callers left to justify inventing a colour for.
//
// The glyph id lives in config/favicon.json, NOT config/icons.json. That other
// file drives registerIcon, and registering a Material glyph overrides the
// ligature font for it — silently disabling the weight/grade/opticalSize
// attributes on that one icon. The font stays authoritative in-app; this
// generator only reads the glyph geometry.
//
// The file favicon.svg replaces carried a hand-copied path from the LEGACY
// Material Icons set. Two grids are in play and they disagree: Iconify NORMALISES
// material-symbols onto 0 0 24 24, while raw Google data and @m3e/icons use
// 0 -960 960 960 (origin at the baseline, negative Y). So geometry is always
// DERIVED from the declared viewBox, never hard-coded — hard-coding it means a
// silent off-canvas glyph the day the source changes. The favicon carries the
// glyph's OWN viewBox through verbatim (no transform can be wrong if there is no
// transform); the OG card, which insets the glyph into a larger canvas, computes
// its placement with plateTransform.

import { writeFileSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";
import { resolveIcon, loadSets } from "./icons-to-js.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..", "..", "..");

const OG_W = 1200;
const OG_H = 630;
const OG_GLYPH = Math.round(OG_H * 0.4); // 252

// A tab icon renders in an ISOLATED document, so `currentColor` resolves to the
// initial `color` — black — which all but disappears against dark browser chrome.
// Light mode is left as pure currentColor; only the dark case names a colour.
const DARK_FILL = "#E6E0E9";

const GRADIENT = `<linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#8A6FE0"/>
      <stop offset="1" stop-color="#5B3F9E"/>
    </linearGradient>`;

/** Round to 7 decimals and strip trailing zeros, so output is stable. */
const num = (n) => String(Number(n.toFixed(7)));

export function plateTransform(viewBox, { plate, glyph, width, height }) {
  const [minX, minY, w, h] = viewBox.trim().split(/\s+/).map(Number);
  if (w !== h) {
    throw new Error(`Glyph viewBox '${viewBox}' is not square; scaling it into the plate would distort it.`);
  }
  const scale = glyph / w;
  const insetX = ((width ?? plate) - glyph) / 2;
  const insetY = ((height ?? plate) - glyph) / 2;
  return `translate(${num(insetX - minX * scale)} ${num(insetY - minY * scale)}) scale(${num(scale)})`;
}

// The bare glyph: no plate, no background, and `currentColor` so the mark takes
// the colour of whatever renders it. `viewBox` is the glyph's own, passed through
// untouched — see the grid note at the top of this file.
export function renderFavicon({ viewBox, path }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="elm-m3e">
  <!-- GENERATED by docs/scripts/icons-gen/brand-images.mjs — do not edit.
       Glyph: material-symbols:palette, the same icon the app bar renders. -->
  <style>@media (prefers-color-scheme: dark) { path { fill: ${DARK_FILL} } }</style>
  <path fill="currentColor" d="${path}"/>
</svg>
`;
}

export function renderOgSvg({ viewBox, path }) {
  const t = plateTransform(viewBox, { glyph: OG_GLYPH, width: OG_W, height: OG_H });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${OG_W} ${OG_H}" role="img" aria-label="elm-m3e">
  <!-- GENERATED by docs/scripts/icons-gen/brand-images.mjs — do not edit. -->
  <defs>
    ${GRADIENT}
  </defs>
  <rect x="0" y="0" width="${OG_W}" height="${OG_H}" fill="url(#g)"/>
  <g transform="${t}">
    <path fill="#FFFFFF" d="${path}"/>
  </g>
</svg>
`;
}

/** PNG bytes for `svg` rendered `size` px wide. */
export function rasterise(svg, size) {
  return new Resvg(svg, { fitTo: { mode: "width", value: size } }).render().asPng();
}

export function glyph() {
  const cfg = JSON.parse(readFileSync(resolve(REPO, "config", "favicon.json"), "utf8"));
  if (!cfg.glyph) throw new Error("config/favicon.json has no `glyph` — the brand glyph is unset.");
  return resolveIcon(loadSets([cfg.glyph.split(":")[0]]), cfg.glyph);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const icon = glyph();
  const out = (n) => resolve(REPO, "docs", "public", n);

  writeFileSync(out("favicon.svg"), renderFavicon(icon));
  console.log(`Wrote favicon.svg (viewBox ${icon.viewBox}).`);

  writeFileSync(out("og-card.png"), rasterise(renderOgSvg(icon), OG_W));
  console.log(`Wrote og-card.png (${OG_W}x${OG_H}).`);
}
