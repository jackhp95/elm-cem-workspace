#!/usr/bin/env node
// gen-svg-modeled-index.mjs — (re)generate docs/svg-audit/modeled-index.json
// from the CURRENT elm-typed-svg package, using the same extractor the
// permanent coverage gate (tools/check-svg-spec-coverage.mjs) reads. Run it
// after any regen of the SVG package so the committed snapshot never drifts
// (the gate fails if it does).
//
// Pure AST/JSON read — no API cost, no package mutation. Writes the file and
// prints the headline counts.
//
// Zero dependencies.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { extractModeled, SVG_PATHS } from "./lib/svg-modeled-extract.mjs";

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(repoRoot, "docs", "svg-audit", "modeled-index.json");

const m = extractModeled(repoRoot);
const today = new Date().toISOString().slice(0, 10);

const doc = {
    _comment:
        "What the elm-typed-svg package actually generates. AST/JSON read of the CURRENT package: manifest tagNames + per-element attrs, config _globals (with which carry a finite `type` enum), Attributes.elm exposing list, Values.elm enum type aliases. Regenerated by tools/gen-svg-modeled-index.mjs; kept honest by tools/check-svg-spec-coverage.mjs. No API cost; no package mutation.",
    source: {
        manifest: SVG_PATHS.manifest,
        config: SVG_PATHS.config,
        attributesElm: SVG_PATHS.attributesElm,
        valuesElm: SVG_PATHS.valuesElm,
        extractedAt: today,
    },
    counts: {
        elements: m.elements.length,
        globalAttributes: m.globals.length,
        typedGlobalEnums: m.globals.filter((g) => g.typed).length,
        attributeSetters: m.attributeSetters.length,
        valuesEnumTypes: m.valuesEnumTypes.length,
    },
    elements: m.elements,
    elementAttributes: m.elementAttributes,
    globals: m.globals,
    attributeSetters: m.attributeSetters,
    valuesEnumTypes: m.valuesEnumTypes,
};

writeFileSync(OUT, JSON.stringify(doc, null, 2) + "\n");
console.log(`gen-svg-modeled-index: wrote ${OUT}`);
console.log(
    `  elements=${doc.counts.elements} globals=${doc.counts.globalAttributes} ` +
        `typedEnums=${doc.counts.typedGlobalEnums} setters=${doc.counts.attributeSetters} ` +
        `valuesEnums=${doc.counts.valuesEnumTypes}`,
);
