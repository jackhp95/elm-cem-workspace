#!/usr/bin/env node
// check-bundle-provenance.mjs — drift gate for cem-figma-connect's facts
// bundle (profiles/m3-kit/facts/{cem-facts,elm-api-facts}.json).
//
// The bundle is a COMMITTED, GENERATED artifact — the workspace producer
// (packages/elm-cem) generated against elm-m3e's own config is the sole
// source of truth (packages/cem-figma-connect/scripts/gen-facts.mjs is the
// only writer). This gate proves the committed copy has not drifted from
// what the producer emits today: regenerate into a scratch directory and
// diff against the tracked copy, byte for byte. This is the same
// drift-gate semantics tools/ab-elm-cem.sh and tools/check-single-cem-facts.mjs
// apply elsewhere in this workspace, applied to this one consumer.
//
// Fails if:
//   - either committed file is missing, or not git-tracked;
//   - regeneration fails to run;
//   - the regenerated bytes differ from the committed bytes (prints a
//     summary of the first differing lines per file, not a silent pass).
//
// Zero dependencies. Exits 0 on success, 1 on any failure.

import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { runFactsGenerator, deriveIconNamesFromOutput, serializeIconNames } from "./lib/regen.mjs";

const repoRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const pkgDir = path.join(repoRoot, "packages", "cem-figma-connect");
const factsDir = path.join(pkgDir, "profiles", "m3-kit", "facts");
const ELM_M3E = process.env.ELM_M3E || path.join(repoRoot, "packages", "elm-m3e");

// cem-facts/elm-api-facts are copied verbatim from the producer's bundle;
// icon-names.json is DERIVED from the producer's Face-A icon module (R-026
// opaque-Name catalog). Both are committed generated artifacts and must not
// drift from a fresh regeneration.
const FILES = ["cem-facts.json", "elm-api-facts.json"];
const ICON_NAMES_FILE = "icon-names.json";

function isGitTracked(absPath) {
    const relPath = path.relative(repoRoot, absPath);
    const result = spawnSync("git", ["ls-files", "--error-unmatch", relPath], { cwd: repoRoot, encoding: "utf8" });
    return result.status === 0;
}

function regenerateBundle(outDir) {
    const outputDir = path.join(outDir, "out");
    const bundleDir = path.join(outDir, "bundle");
    fs.mkdirSync(outputDir, { recursive: true });
    fs.mkdirSync(bundleDir, { recursive: true });

    const result = runFactsGenerator({ repoRoot, elmM3e: ELM_M3E, output: outputDir, factsBundle: bundleDir });
    if (result.stdout) process.stdout.write(result.stdout);
    if (result.stderr) process.stderr.write(result.stderr);
    if (result.status !== 0) {
        throw new Error(`elm-cem --facts-bundle exited ${result.status}`);
    }
    return { outputDir, bundleDir };
}

function diffSummary(committedPath, freshPath) {
    try {
        return execFileSync("diff", ["-u", committedPath, freshPath], { encoding: "utf8" });
    } catch (e) {
        // diff exits 1 when files differ; its stdout still carries the unified diff.
        return e.stdout || e.message;
    }
}

function main() {
    console.log(`check-bundle-provenance: policing ${path.relative(repoRoot, factsDir)}`);

    const failures = [];

    for (const file of [...FILES, ICON_NAMES_FILE]) {
        const committedPath = path.join(factsDir, file);
        if (!fs.existsSync(committedPath)) {
            failures.push(`${path.relative(repoRoot, committedPath)} is missing.`);
            continue;
        }
        if (!isGitTracked(committedPath)) {
            failures.push(`${path.relative(repoRoot, committedPath)} exists but is not git-tracked.`);
        }
    }

    if (!fs.existsSync(ELM_M3E)) {
        failures.push(`elm-m3e checkout not found at ${ELM_M3E} (set ELM_M3E).`);
    }

    if (failures.length > 0) {
        console.error(`\ncheck-bundle-provenance: FAIL — ${failures.length} problem(s) before regeneration:`);
        for (const f of failures) console.error(`  - ${f}`);
        process.exit(1);
    }

    const work = fs.mkdtempSync(path.join(os.tmpdir(), "check-bundle-provenance-"));
    try {
        console.log(`check-bundle-provenance: regenerating from the producer (elm-cem) against ${path.relative(repoRoot, ELM_M3E)}'s config...`);
        let outputDir, bundleDir;
        try {
            ({ outputDir, bundleDir } = regenerateBundle(work));
        } catch (e) {
            console.error(`\ncheck-bundle-provenance: FAIL — regeneration threw: ${e.message}`);
            process.exit(1);
        }

        for (const file of FILES) {
            const committedPath = path.join(factsDir, file);
            const freshPath = path.join(bundleDir, file);
            if (!fs.existsSync(freshPath)) {
                failures.push(`regeneration did not produce ${file}.`);
                continue;
            }
            const committedBytes = fs.readFileSync(committedPath);
            const freshBytes = fs.readFileSync(freshPath);
            if (!committedBytes.equals(freshBytes)) {
                const summary = diffSummary(committedPath, freshPath);
                const lines = summary.split("\n").slice(0, 40).join("\n");
                failures.push(
                    `${path.relative(repoRoot, committedPath)} DRIFTED from what the producer generates today. ` +
                        `Committed copy no longer matches elm-cem's output — regenerate via ` +
                        `\`pnpm --filter cem-figma-connect run gen:facts\` and commit the result. First diff lines:\n${lines}`,
                );
                continue;
            }
            console.log(`  ok  ${file} — byte-identical to a fresh regeneration.`);
        }

        // The opaque-Name icon catalog is DERIVED from the fresh Face-A output
        // (not the bundle) via the same deriveIconNames the writer uses.
        {
            const committedPath = path.join(factsDir, ICON_NAMES_FILE);
            let freshBytes;
            try {
                freshBytes = Buffer.from(serializeIconNames(deriveIconNamesFromOutput(outputDir)), "utf8");
            } catch (e) {
                failures.push(`could not derive ${ICON_NAMES_FILE} from the fresh output: ${e.message}`);
                freshBytes = null;
            }
            if (freshBytes) {
                const committedBytes = fs.readFileSync(committedPath);
                if (!committedBytes.equals(freshBytes)) {
                    const freshPath = path.join(work, ICON_NAMES_FILE);
                    fs.writeFileSync(freshPath, freshBytes);
                    const summary = diffSummary(committedPath, freshPath);
                    const lines = summary.split("\n").slice(0, 40).join("\n");
                    failures.push(
                        `${path.relative(repoRoot, committedPath)} DRIFTED from what the producer generates today. ` +
                            `Regenerate via \`pnpm --filter cem-figma-connect run gen:facts\` and commit the result. First diff lines:\n${lines}`,
                    );
                } else {
                    console.log(`  ok  ${ICON_NAMES_FILE} — byte-identical to a fresh derivation.`);
                }
            }
        }
    } finally {
        fs.rmSync(work, { recursive: true, force: true });
    }

    if (failures.length > 0) {
        console.error(`\ncheck-bundle-provenance: FAIL — ${failures.length} problem(s):`);
        for (const f of failures) console.error(`  - ${f}`);
        process.exit(1);
    }

    console.log("\ncheck-bundle-provenance: OK — committed facts bundle is git-tracked and byte-identical to the producer's current output.");
}

main();
