#!/usr/bin/env node
// check-bundle-provenance-m3e-okf.mjs — drift gate for m3e-okf's facts bundle
// copy (packages/m3e-okf/data/cem-facts.json).
//
// The bundle is a COMMITTED, GENERATED artifact — the workspace producer
// (packages/elm-cem) generated against elm-m3e's own config is the sole
// source of truth (packages/m3e-okf/scripts/gen-facts.mjs is the only
// writer). This gate proves the committed copy has not drifted from what the
// producer emits today: regenerate into a scratch directory and diff against
// the tracked copy, byte for byte. This is the same drift-gate semantics
// tools/ab-elm-cem.sh, tools/check-single-cem-facts.mjs, and
// tools/check-bundle-provenance.mjs (cem-figma-connect's) apply elsewhere in
// this workspace, applied to this one consumer.
//
// Fails if:
//   - the committed file is missing, or not git-tracked;
//   - regeneration fails to run;
//   - the regenerated bytes differ from the committed bytes (prints a
//     summary of the first differing lines, not a silent pass).
//
// Zero dependencies. Exits 0 on success, 1 on any failure.

import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { runFactsGenerator } from "./lib/regen.mjs";

const repoRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const pkgDir = path.join(repoRoot, "packages", "m3e-okf");
const committedPath = path.join(pkgDir, "data", "cem-facts.json");
const ELM_M3E = process.env.ELM_M3E || path.join(repoRoot, "packages", "elm-m3e");

function isGitTracked(absPath) {
    const relPath = path.relative(repoRoot, absPath);
    const result = spawnSync("git", ["ls-files", "--error-unmatch", relPath], { cwd: repoRoot, encoding: "utf8" });
    return result.status === 0;
}

function regenerateBundle(outDir) {
    const outputDir = path.join(outDir, "out");
    const bundleDir = path.join(outDir, "bundle");
    fs.mkdirSync(outputDir, { recursive: true });
    fs.mkdirSync(bundleDir, { recursive: true });

    const result = runFactsGenerator({ repoRoot, elmM3e: ELM_M3E, output: outputDir, factsBundle: bundleDir });
    if (result.stdout) process.stdout.write(result.stdout);
    if (result.stderr) process.stderr.write(result.stderr);
    if (result.status !== 0) {
        throw new Error(`elm-cem --facts-bundle exited ${result.status}`);
    }
    return path.join(bundleDir, "cem-facts.json");
}

function diffSummary(committed, fresh) {
    try {
        return execFileSync("diff", ["-u", committed, fresh], { encoding: "utf8" });
    } catch (e) {
        // diff exits 1 when files differ; its stdout still carries the unified diff.
        return e.stdout || e.message;
    }
}

function main() {
    console.log(`check-bundle-provenance-m3e-okf: policing ${path.relative(repoRoot, committedPath)}`);

    const failures = [];

    if (!fs.existsSync(committedPath)) {
        failures.push(`${path.relative(repoRoot, committedPath)} is missing.`);
    } else if (!isGitTracked(committedPath)) {
        failures.push(`${path.relative(repoRoot, committedPath)} exists but is not git-tracked.`);
    }

    if (!fs.existsSync(ELM_M3E)) {
        failures.push(`elm-m3e checkout not found at ${ELM_M3E} (set ELM_M3E).`);
    }

    if (failures.length > 0) {
        console.error(`\ncheck-bundle-provenance-m3e-okf: FAIL — ${failures.length} problem(s) before regeneration:`);
        for (const f of failures) console.error(`  - ${f}`);
        process.exit(1);
    }

    const work = fs.mkdtempSync(path.join(os.tmpdir(), "check-bundle-provenance-m3e-okf-"));
    try {
        console.log(`check-bundle-provenance-m3e-okf: regenerating from the producer (elm-cem) against ${path.relative(repoRoot, ELM_M3E)}'s config...`);
        let freshPath;
        try {
            freshPath = regenerateBundle(work);
        } catch (e) {
            console.error(`\ncheck-bundle-provenance-m3e-okf: FAIL — regeneration threw: ${e.message}`);
            process.exit(1);
        }

        if (!fs.existsSync(freshPath)) {
            failures.push("regeneration did not produce cem-facts.json.");
        } else {
            const committedBytes = fs.readFileSync(committedPath);
            const freshBytes = fs.readFileSync(freshPath);
            if (!committedBytes.equals(freshBytes)) {
                const summary = diffSummary(committedPath, freshPath);
                const lines = summary.split("\n").slice(0, 40).join("\n");
                failures.push(
                    `${path.relative(repoRoot, committedPath)} DRIFTED from what the producer generates today. ` +
                        `Committed copy no longer matches elm-cem's output — regenerate via ` +
                        `\`pnpm --filter m3e-docs run gen:facts\` and commit the result. First diff lines:\n${lines}`,
                );
            } else {
                console.log(`  ok  data/cem-facts.json — byte-identical to a fresh regeneration.`);
            }
        }
    } finally {
        fs.rmSync(work, { recursive: true, force: true });
    }

    if (failures.length > 0) {
        console.error(`\ncheck-bundle-provenance-m3e-okf: FAIL — ${failures.length} problem(s):`);
        for (const f of failures) console.error(`  - ${f}`);
        process.exit(1);
    }

    console.log("\ncheck-bundle-provenance-m3e-okf: OK — committed facts bundle is git-tracked and byte-identical to the producer's current output.");
}

main();
